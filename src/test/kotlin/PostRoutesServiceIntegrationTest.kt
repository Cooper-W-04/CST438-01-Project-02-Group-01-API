package com.scheduler

import com.scheduler.service.AlreadyMemberException
import com.scheduler.service.GroupNotFoundException
import com.scheduler.service.PostRoutesService
import org.junit.jupiter.api.BeforeEach
import org.junit.jupiter.api.Test
import org.springframework.jdbc.core.JdbcTemplate
import org.springframework.jdbc.datasource.DriverManagerDataSource
import org.testcontainers.containers.PostgreSQLContainer
import org.testcontainers.junit.jupiter.Container
import org.testcontainers.junit.jupiter.Testcontainers
import kotlin.test.assertEquals
import kotlin.test.assertFailsWith

@Testcontainers
class PostRoutesServiceIntegrationTest {

    companion object {
        @Container
        @JvmStatic
        val postgres = PostgreSQLContainer<Nothing>("postgres:16-alpine")
    }

    private lateinit var jdbcTemplate: JdbcTemplate
    private lateinit var postRoutesService: PostRoutesService

    @BeforeEach
    fun setUp() {
        val dataSource = DriverManagerDataSource().apply {
            setDriverClassName("org.postgresql.Driver")
            url = postgres.jdbcUrl
            username = postgres.username
            password = postgres.password
        }

        jdbcTemplate = JdbcTemplate(dataSource)
        postRoutesService = PostRoutesService(jdbcTemplate)

        createTables()
        insertTestUsers()
    }

    private fun createTables() {
        jdbcTemplate.execute(
            """
            DROP TABLE IF EXISTS group_members, schedule_groups, users CASCADE
            """.trimIndent()
        )

        jdbcTemplate.execute(
            """
            CREATE TABLE users (
                id BIGINT PRIMARY KEY,
                oauth_provider TEXT NOT NULL,
                oauth_subject TEXT NOT NULL,
                display_name TEXT NOT NULL,
                role TEXT NOT NULL DEFAULT 'USER',
                created_at TIMESTAMPTZ NOT NULL DEFAULT now()
            )
            """.trimIndent()
        )

        jdbcTemplate.execute(
            """
            CREATE TABLE schedule_groups (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                event_name TEXT NOT NULL,
                created_by BIGINT NOT NULL,
                created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
                FOREIGN KEY (created_by)
                    REFERENCES users(id)
                    ON DELETE CASCADE
            )
            """.trimIndent()
        )

        jdbcTemplate.execute(
            """
            CREATE TABLE group_members (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                group_id BIGINT NOT NULL,
                user_id BIGINT NOT NULL,
                joined_at TIMESTAMPTZ NOT NULL DEFAULT now(),
                FOREIGN KEY (group_id)
                    REFERENCES schedule_groups(id)
                    ON DELETE CASCADE,
                FOREIGN KEY (user_id)
                    REFERENCES users(id)
                    ON DELETE CASCADE,
                UNIQUE (group_id, user_id)
            )
            """.trimIndent()
        )
    }

    private fun insertTestUsers() {
        jdbcTemplate.update(
            """
            INSERT INTO users
                (id, oauth_provider, oauth_subject, display_name, role)
            VALUES
                (1, 'test', 'subject-1', 'Test User One', 'USER'),
                (2, 'test', 'subject-2', 'Test User Two', 'USER')
            """.trimIndent()
        )
    }

    @Test
    fun `creating a group stores the group and creator`() {
        val createdGroup = postRoutesService.createGroup(
            eventName = "Test Event",
            userId = 1L
        )

        assertEquals("Test Event", createdGroup.eventName)
        assertEquals(1L, createdGroup.createdBy)
        assertEquals(1, count("schedule_groups", "event_name = 'Test Event'"))
    }

    @Test
    fun `joining a group creates a membership`() {
        val group = postRoutesService.createGroup(
            eventName = "Test Event",
            userId = 1L
        )

        val membership = postRoutesService.joinGroup(
            groupId = group.id,
            userId = 2L
        )

        assertEquals(group.id, membership.groupId)
        assertEquals(2L, membership.userId)
        assertEquals(
            1,
            count(
                "group_members",
                "group_id = ${group.id} AND user_id = 2"
            )
        )
    }

    @Test
    fun `joining the same group twice is rejected`() {
        val group = postRoutesService.createGroup(
            eventName = "Test Event",
            userId = 1L
        )

        postRoutesService.joinGroup(
            groupId = group.id,
            userId = 2L
        )

        assertFailsWith<AlreadyMemberException> {
            postRoutesService.joinGroup(
                groupId = group.id,
                userId = 2L
            )
        }
    }

    @Test
    fun `joining a nonexistent group is rejected`() {
        assertFailsWith<GroupNotFoundException> {
            postRoutesService.joinGroup(
                groupId = 999L,
                userId = 2L
            )
        }
    }

    @Test
    fun `creating a group with a blank name is rejected`() {
        assertFailsWith<IllegalArgumentException> {
            postRoutesService.createGroup(
                eventName = "   ",
                userId = 1L
            )
        }
    }

    private fun count(
        table: String,
        condition: String
    ): Int {
        return jdbcTemplate.queryForObject(
            "SELECT COUNT(*) FROM $table WHERE $condition",
            Int::class.java
        ) ?: 0
    }
}